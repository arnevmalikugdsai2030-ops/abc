"""
Master Visibility Oracle for MIRRORLAB.

Synthesizes the complete deterministic computational geometry pipeline:
1. Direct sightline occlusion check (C -> T)
2. Specular reflection & finite mirror clipping (Virtual-Target Method)
3. Camera angular Field of View (FOV) cone validation
4. Two-leg obstacle occlusion testing (Leg 1: C -> R, Leg 2: R -> T)

Returns a unified, fully typed evaluation result with exact reason codes.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, field

import numpy as np

from mirrorlab.geometry.camera import CameraFOVResult, validate_camera_fov
from mirrorlab.geometry.obstacles import (
    ObstacleBase,
    ObstacleHit,
    PathLeg,
    PathOcclusionResult,
    check_segment_occlusion,
    check_two_leg_path_occlusion,
)
from mirrorlab.geometry.reflection import (
    MirrorReflectionResult,
    ReflectionFailureReason,
    calculate_mirror_reflection,
)
from mirrorlab.geometry.vector import EPSILON, _to_vec2
from mirrorlab.schema.common import ObstructionReason, VisibilityState

ArrayLike = Sequence[float] | np.ndarray


@dataclass(frozen=True)
class VisibilityOracleResult:
    """
    Comprehensive ground-truth verdict generated by the deterministic geometry oracle.
    """

    # Core Verdict
    state: VisibilityState
    is_visible: bool
    reason: ObstructionReason
    diagnostic_details: str

    # Direct line-of-sight metrics (Camera directly to Target)
    is_direct_sight_blocked: bool
    direct_sight_hit: ObstacleHit | None = None

    # Mirror reflection metrics
    reflection_result: MirrorReflectionResult | None = None
    reflection_point: np.ndarray | None = None
    virtual_target: np.ndarray | None = None

    # Camera FOV metrics
    fov_result: CameraFOVResult | None = None
    is_in_camera_fov: bool = False

    # Obstacle occlusion metrics
    occlusion_result: PathOcclusionResult | None = None
    blocking_obstacle_hit: ObstacleHit | None = None

    # Full verified optical path
    path_points: list[np.ndarray] = field(default_factory=list)
    total_optical_distance: float | None = None
    incident_angle_deg: float | None = None
    reflected_angle_deg: float | None = None


def evaluate_visibility_oracle(
    camera_pos: ArrayLike,
    camera_forward: ArrayLike | float,
    camera_fov_degrees: float,
    target_pos: ArrayLike,
    mirror_a: ArrayLike,
    mirror_b: ArrayLike,
    obstacles: Sequence[ObstacleBase] | None = None,
    reflective_normal: ArrayLike | None = None,
    trim_epsilon: float = 1e-4,
    eps: float = EPSILON,
) -> VisibilityOracleResult:
    """
    Determine whether the camera can inspect the target scratch via specular reflection
    in the finite flat mirror.

    Evaluation Pipeline:
    1. Direct Line-of-Sight Check: Test segment C -> T against obstacles.
    2. Mirror Reflection: Calculate reflection point R using the virtual-target method.
       - If camera or target is on the back side -> BACK_OF_MIRROR
       - If reflection misses mirror segment -> MISSED_MIRROR
    3. Camera FOV Check: Test if outgoing ray C -> R is inside camera's FOV.
       - If outside -> OUT_OF_FOV
    4. Two-Leg Obstacle Occlusion:
       - If Leg 1 (C -> R) blocked -> BLOCKED_INCIDENT
       - If Leg 2 (R -> T) blocked -> BLOCKED_REFLECTED
    5. Success: If all checks pass -> VISIBLE, reason NONE.

    Args:
        camera_pos: [x, y] coordinates of camera.
        camera_forward: Vector [dx, dy] or heading angle in degrees.
        camera_fov_degrees: Field of view cone angle in degrees.
        target_pos: [x, y] coordinates of target scratch.
        mirror_a: [x, y] first endpoint of mirror.
        mirror_b: [x, y] second endpoint of mirror.
        obstacles: Optional list of circular or rectangular obstacles.
        reflective_normal: Optional normal hint vector defining reflective side.
        trim_epsilon: Endpoint tolerance in mm to prevent self-occlusion.
        eps: Numerical guard.

    Returns:
        VisibilityOracleResult: Absolute mathematical ground truth.
    """
    c = _to_vec2(camera_pos, "camera_pos")
    tgt = _to_vec2(target_pos, "target_pos")
    obs_list = list(obstacles) if obstacles is not None else []

    # Step 1: Compute specular reflection on mirror
    refl_res = calculate_mirror_reflection(
        c,
        tgt,
        mirror_a,
        mirror_b,
        reflective_normal=reflective_normal,
        eps=eps,
    )

    # If mirror reflection itself failed (e.g. wrong side or missed mirror)
    if not refl_res.is_valid:
        # Check direct sightline anyway for diagnostic completeness
        dir_hit = check_segment_occlusion(
            c,
            tgt,
            obs_list,
            leg=PathLeg.DIRECT_CAMERA_TO_TARGET,
            trim_epsilon=trim_epsilon,
        )
        is_dir_blocked = dir_hit is not None

        if refl_res.failure_reason in (
            ReflectionFailureReason.WRONG_SIDE_CAMERA,
            ReflectionFailureReason.WRONG_SIDE_TARGET,
            ReflectionFailureReason.WRONG_SIDE_BOTH,
        ):
            reason = ObstructionReason.BACK_OF_MIRROR
            diag = f"Reflection failed: {refl_res.failure_reason.value}"
        elif refl_res.failure_reason in (
            ReflectionFailureReason.MISSED_MIRROR_PAST_A,
            ReflectionFailureReason.MISSED_MIRROR_PAST_B,
        ):
            reason = ObstructionReason.MISSED_MIRROR
            diag = f"Ray misses finite mirror (t_mirror={refl_res.mirror_t:.3f})"
        else:
            reason = ObstructionReason.MISSED_MIRROR
            diag = f"Geometric failure: {refl_res.failure_reason}"

        return VisibilityOracleResult(
            state=VisibilityState.NOT_VISIBLE,
            is_visible=False,
            reason=reason,
            diagnostic_details=diag,
            is_direct_sight_blocked=is_dir_blocked,
            direct_sight_hit=dir_hit,
            reflection_result=refl_res,
            reflection_point=refl_res.intersection_point,
            virtual_target=refl_res.virtual_target,
        )

    r = refl_res.intersection_point
    assert r is not None

    # Step 2: Camera Field-of-View Check (Camera looking towards reflection point R)
    fov_res = validate_camera_fov(c, camera_forward, camera_fov_degrees, r, eps=eps)

    if not fov_res.is_inside:
        dir_hit = check_segment_occlusion(
            c,
            tgt,
            obs_list,
            leg=PathLeg.DIRECT_CAMERA_TO_TARGET,
            trim_epsilon=trim_epsilon,
        )
        is_dir_blocked = dir_hit is not None

        return VisibilityOracleResult(
            state=VisibilityState.NOT_VISIBLE,
            is_visible=False,
            reason=ObstructionReason.OUT_OF_FOV,
            diagnostic_details=(
                f"Mirror point ({r[0]:.1f}, {r[1]:.1f}) is outside FOV: "
                f"angle={fov_res.angle_to_heading_deg:.1f} deg > half_fov={fov_res.fov_half_angle_deg:.1f} deg"
            ),
            is_direct_sight_blocked=is_dir_blocked,
            direct_sight_hit=dir_hit,
            reflection_result=refl_res,
            reflection_point=r,
            virtual_target=refl_res.virtual_target,
            fov_result=fov_res,
            is_in_camera_fov=False,
        )

    # Step 3: Two-Leg Obstacle Occlusion Check
    occl_res = check_two_leg_path_occlusion(
        c, r, tgt, obs_list, trim_epsilon=trim_epsilon
    )

    if occl_res.is_path_blocked:
        assert occl_res.first_blocker is not None
        hit = occl_res.first_blocker
        if hit.leg == PathLeg.LEG_1_CAMERA_TO_MIRROR:
            reason = ObstructionReason.BLOCKED_INCIDENT
            diag = f"Incident ray C->R blocked by obstacle '{hit.obstacle_id}' at ({hit.hit_point[0]:.1f}, {hit.hit_point[1]:.1f})"
        else:
            reason = ObstructionReason.BLOCKED_REFLECTED
            diag = f"Reflected ray R->T blocked by obstacle '{hit.obstacle_id}' at ({hit.hit_point[0]:.1f}, {hit.hit_point[1]:.1f})"

        return VisibilityOracleResult(
            state=VisibilityState.NOT_VISIBLE,
            is_visible=False,
            reason=reason,
            diagnostic_details=diag,
            is_direct_sight_blocked=occl_res.is_direct_sight_blocked,
            direct_sight_hit=occl_res.direct_sight_hit,
            reflection_result=refl_res,
            reflection_point=r,
            virtual_target=refl_res.virtual_target,
            fov_result=fov_res,
            is_in_camera_fov=True,
            occlusion_result=occl_res,
            blocking_obstacle_hit=hit,
        )

    # Step 4: Full Success!
    inc_deg = (
        np.degrees(refl_res.incident_angle_rad)
        if refl_res.incident_angle_rad is not None
        else None
    )
    refl_deg = (
        np.degrees(refl_res.reflected_angle_rad)
        if refl_res.reflected_angle_rad is not None
        else None
    )

    return VisibilityOracleResult(
        state=VisibilityState.VISIBLE,
        is_visible=True,
        reason=ObstructionReason.NONE,
        diagnostic_details=(
            f"Unobstructed optical sightline via mirror at ({r[0]:.1f}, {r[1]:.1f}) with theta_i=theta_r={inc_deg:.1f} deg"
        ),
        is_direct_sight_blocked=occl_res.is_direct_sight_blocked,
        direct_sight_hit=occl_res.direct_sight_hit,
        reflection_result=refl_res,
        reflection_point=r,
        virtual_target=refl_res.virtual_target,
        fov_result=fov_res,
        is_in_camera_fov=True,
        occlusion_result=occl_res,
        path_points=[c, r, tgt],
        total_optical_distance=refl_res.total_path_length,
        incident_angle_deg=inc_deg,
        reflected_angle_deg=refl_deg,
    )
